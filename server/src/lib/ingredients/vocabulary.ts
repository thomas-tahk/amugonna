function titleCase(s: string): string {
  const small = new Set(['of', 'and', 'in', 'with']);
  return s
    .split(' ')
    .map((w, i) =>
      i > 0 && small.has(w)
        ? w
        : w
            .split('-')
            .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
            .join('-'),
    )
    .join(' ');
}

function parseLine(line: string, category: Category): VocabEntry {
  const flags = new Map<string, string>();
  const body = line.replace(/@(\w+)(?:=([^@|]*))?/g, (_m, k: string, v?: string) => {
    flags.set(k, (v ?? '').trim());
    return '';
  });
  const [head, syns = ''] = body.split('|');
  const [canonicalRaw, parentRaw] = head.split('>').map((x) => x.trim());
  const canonical = canonicalRaw.toLowerCase();
  return {
    canonical,
    name: flags.get('name') || titleCase(canonical),
    category,
    synonyms: syns
      .split(',')
      .map((x) => x.trim().toLowerCase())
      .filter(Boolean),
    parent: parentRaw ? parentRaw.toLowerCase() : undefined,
    staple: flags.has('staple'),
    common: flags.has('common'),
    generic: flags.has('generic') || undefined,
    satisfiedBy: flags.has('needs') ? flags.get('needs')!.split('/').map((x) => x.trim().toLowerCase()) : undefined,
  };
}

function build(): readonly VocabEntry[] {
  const parsed: VocabEntry[] = [];
  for (const category of CATEGORIES) {
    for (const line of RAW[category]) parsed.push(parseLine(line, category));
  }
  const stapleCanon = new Set(parsed.filter((e) => e.staple).map((e) => e.canonical));
  // staple is inherited from the parent family (cooking oil -> olive oil, ...)
  return Object.freeze(
    parsed.map((e) =>
      Object.freeze({
        ...e,
        staple: e.staple || (e.parent !== undefined && stapleCanon.has(e.parent)),
        synonyms: Object.freeze([...e.synonyms]),
      }),
    ),
  );
}

const VOCABULARY: readonly VocabEntry[] = build();
const BY_CANONICAL: ReadonlyMap<string, VocabEntry> = new Map(VOCABULARY.map((e) => [e.canonical, e]));

export function getVocabulary(): readonly VocabEntry[] {
  return VOCABULARY;
}

export function getEntry(canonical: string): VocabEntry | undefined {
  return BY_CANONICAL.get(canonical);
}

/** The quick-pick grid: common entries grouped by category, in CATEGORIES order. */
export function getCommon(): { category: Category; entries: VocabEntry[] }[] {
  return CATEGORIES.map((category) => ({
    category,
    entries: VOCABULARY.filter((e) => e.common && e.category === category),
  })).filter((g) => g.entries.length > 0);
}
